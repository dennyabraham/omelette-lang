local h = require("spec.support.harness")
local parser = require("omelette.parser")
local typecheck = require("omelette.typecheck")
local names = require("omelette.lsp.names")

local function index(src)
  local _, binding_of = typecheck.check(parser.parse_all(src).program)
  return names.index(binding_of)
end

h.describe("lsp name occurrences", function()
  h.it("finds a use and its declaration by position", function()
    local idx = index("let f x = x")
    local use = names.at(idx, 1, 11)
    h.eq(use.is_decl, false)
    h.eq({ use.decl.line, use.decl.col }, { 1, 7 })
    local decl = names.at(idx, 1, 7)
    h.eq(decl.is_decl, true)
    h.eq(decl.decl, use.decl)
    h.eq(names.at(idx, 1, 9), nil)
  end)
  h.it("finds a declaration that has no uses", function()
    h.eq(names.at(index("let n = 1"), 1, 5).is_decl, true)
  end)
  h.it("spans a constructor use by its tag", function()
    local idx = index("type T = | A | B\nlet v = A")
    h.eq(names.at(idx, 2, 9).decl.kind, "enumMember")
    h.eq(names.at(idx, 2, 10), nil)
  end)
end)
