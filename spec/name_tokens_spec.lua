local h = require("spec.support.harness")
local parser = require("omelette.parser")

local function first(src) return assert(parser.parse(src)).stmts[1] end
local function at(t) return { t.value, t.line, t.col } end

h.describe("name tokens", function()
  h.it("keeps a let's name and parameters", function()
    local s = first("let f (x : number) y = x")
    h.eq(at(s.name_tok), { "f", 1, 5 })
    h.eq(at(s.param_toks[1]), { "x", 1, 8 })
    h.eq(at(s.param_toks[2]), { "y", 1, 20 })
  end)
  h.it("keeps a value binding's name", function()
    local s = first("let v = 1")
    h.eq(at(s.name_tok), { "v", 1, 5 })
    h.eq(s.param_toks, nil)
  end)
  h.it("keeps a lambda's parameters", function()
    local s = first("let g = fn a b -> a").value
    h.eq(at(s.param_toks[2]), { "b", 1, 14 })
  end)
  h.it("keeps a type declaration's name and its variants' names", function()
    local s = first("type Shape = | Circle { r } | Dot")
    h.eq(at(s.name_tok), { "Shape", 1, 6 })
    h.eq(at(s.variants[1].name_tok), { "Circle", 1, 16 })
    h.eq(at(s.variants[2].name_tok), { "Dot", 1, 31 })
  end)
  h.it("keeps field keys in records, constructors and updates", function()
    h.eq(at(first("{ x = 1 }").fields[1].key_tok), { "x", 1, 3 })
    h.eq(at(first("P { x = 1 }").fields[1].key_tok), { "x", 1, 5 })
    h.eq(at(first("{ r with x = 1 }").fields[1].key_tok), { "x", 1, 10 })
  end)
  h.it("keeps field keys in record and constructor patterns", function()
    h.eq(at(first("let m = match r with | { x } -> x").value.cases[1].pattern.fields[1].key_tok), { "x", 1, 26 })
    h.eq(at(first("let m = match r with | P { x } -> x").value.cases[1].pattern.fields[1].key_tok), { "x", 1, 28 })
  end)
  h.it("keeps the name of a field access", function()
    h.eq(at(first("r.x").name_tok), { "x", 1, 3 })
  end)
  h.it("keeps generator names", function()
    h.eq(at(first("[ x | x <- xs ]").quals[1].name_tok), { "x", 1, 7 })
    local g = first("{ k => v | k, v <- t }").quals[1]
    h.eq(at(g.name_tok), { "k", 1, 12 })
    h.eq(at(g.value_name_tok), { "v", 1, 15 })
  end)
end)
