local h = require("spec.support.harness")
local errors = require("omelette.errors")
local lexer = require("omelette.lexer")
local parser = require("omelette.parser")
local compiler = require("omelette.compiler")

local function span(d) return { d.line, d.col, d.end_line, d.end_col } end

h.describe("diagnostic end positions", function()
  h.it("defaults to one column past the start", function()
    h.eq(span(errors.new("m", 2, 3)), { 2, 3, 2, 4 })
  end)
  h.it("keeps an explicit end", function()
    h.eq(span(errors.new("m", 2, 3, nil, 4, 1)), { 2, 3, 4, 1 })
  end)
  h.it("spans an unexpected character", function()
    local r = lexer.tokenize("let a = 1 @ 2", { recover = true })
    h.eq(span(r.diagnostics[1]), { 1, 11, 1, 12 })
  end)
  h.it("reports a multi-byte character once, across all its bytes", function()
    local r = lexer.tokenize("let x = \240\159\152\128 + 1", { recover = true })
    h.eq(#r.diagnostics, 1)
    h.eq(span(r.diagnostics[1]), { 1, 9, 1, 13 })
    h.eq(r.diagnostics[1].message, "unexpected character '\240\159\152\128'")
  end)
  h.it("shows a byte that is not UTF-8 as an escape", function()
    local r = lexer.tokenize("let x = 1 \255 y", { recover = true })
    h.eq(#r.diagnostics, 1)
    h.eq(span(r.diagnostics[1]), { 1, 11, 1, 12 })
    h.eq(r.diagnostics[1].message, "unexpected character '\\xff'")
  end)
  h.it("spans an unterminated string to the end of its line", function()
    local r = lexer.tokenize('let s = "abc\nlet t = 1', { recover = true })
    h.eq(span(r.diagnostics[1]), { 1, 9, 1, 13 })
  end)
  h.it("ends a comment on a CRLF line before the \\r (#41)", function()
    local c = lexer.tokenize("x -- c\r\ny", { recover = true }).comments[1]
    h.eq({ c.text, c.end_line, c.end_col }, { "-- c", 1, 7 })
  end)
  h.it("ends an unterminated string on a CRLF line before the \\r (#41)", function()
    local r = lexer.tokenize('let s = "abc\r\nlet t = 1', { recover = true })
    h.eq(span(r.diagnostics[1]), { 1, 9, 1, 13 })
    local s = r.tokens[4]
    h.eq({ s.type, s.value, s.end_col }, { "string", "abc", 13 })
    h.eq(r.tokens[5].value, "let")
  end)
  h.it("spans the token a parse error is at", function()
    h.eq(span(parser.parse_all("let b = )").diagnostics[1]), { 1, 9, 1, 10 })
  end)
  h.it("spans the last token of an unfinished statement", function()
    h.eq(span(parser.parse_all("let x =\nlet y = 2\n").diagnostics[1]), { 1, 7, 1, 8 })
  end)
  h.it("ends a type error at the end of its node", function()
    local d = compiler.check('let n : number = "s"')[1]
    h.eq(d.message, "'n' is declared number but assigned string")
    h.eq({ d.end_line, d.end_col }, { 1, 21 })
  end)
end)

-- #43: positions the default lexer changed in sub-project 1
h.describe("lexer positions in the default mode", function()
  h.it("gives a multi-line string the line it starts on", function()
    local toks = assert(lexer.tokenize('"a\nb"'))
    h.eq(toks[1].line, 1)
  end)
  h.it("reports an unterminated string at the line it starts on", function()
    local _, err = lexer.tokenize('x = "abc\ndef')
    h.eq({ err.line, err.col }, { 1, 5 })
  end)
  h.it("processes escapes in an unterminated string, as in a terminated one (#42)", function()
    local r = lexer.tokenize('let s = "a\\nb\\"c\nlet t = 1', { recover = true })
    h.eq(r.tokens[4].type, "string")
    h.eq(r.tokens[4].value, 'a\nb"c')
  end)
end)
