local h = require("spec.support.harness")
local json = require("omelette.json")

h.describe("json", function()
  h.it("round-trips objects, arrays, booleans and null", function()
    local v = { a = 1, b = { true, false, json.null }, c = "x" }
    local back = assert(json.decode(json.encode(v)))
    h.eq(back.a, 1)
    h.eq(back.c, "x")
    h.eq(back.b[1], true)
    h.eq(back.b[2], false)
    h.eq(back.b[3], json.null)
  end)
  h.it("encodes a marked empty table as an array and an unmarked one as an object", function()
    h.eq(json.encode(json.array({})), "[]")
    h.eq(json.encode({}), "{}")
  end)
  h.it("encodes whole numbers without a decimal point", function()
    h.eq(json.encode(3), "3")
    h.eq(json.encode(0.5), "0.5")
    h.eq(json.encode(-12), "-12")
  end)
  h.it("escapes quotes, backslashes and control characters", function()
    h.eq(json.encode("a\"b\\\n\1"), '"a\\"b\\\\\\n\\u0001"')
  end)
  h.it("passes other bytes through", function()
    h.eq(json.encode("é"), '"é"')
  end)
  h.it("decodes \\u escapes, including surrogate pairs", function()
    h.eq(json.decode('"\\u00e9"'), "é")
    h.eq(json.decode('"\\ud83d\\ude00"'), "\240\159\152\128")
    h.eq(json.decode('"a\\nb\\/"'), "a\nb/")
  end)
  h.it("returns an error for invalid input without throwing", function()
    for _, text in ipairs({ "[1, 2", '{"a" 1}', "", "tru", '"abc', "[1,]" }) do
      local v, err = json.decode(text)
      h.eq(v, nil)
      h.eq(type(err), "string")
    end
  end)
  h.it("marks decoded arrays so they re-encode as arrays", function()
    local v = assert(json.decode('  {"a": [ ] }  '))
    h.eq(json.encode(v.a), "[]")
  end)
  h.it("encodes NaN and infinities as null", function()
    h.eq(json.encode({ 0 / 0, math.huge, -math.huge }), "[null,null,null]")
  end)
  h.it("decodes numbers", function()
    h.eq(json.decode("[1, -2.5, 3e2]")[3], 300)
    h.eq(json.decode("-2.5"), -2.5)
  end)
end)
