local h = require("spec.support.harness")
local lexer = require("omelette.lexer")

local function ends(t) return { t.end_line, t.end_col } end

h.describe("lexer: end positions", function()
  h.it("records where each token ends", function()
    local toks = assert(lexer.tokenize("x + 12"))
    h.eq(ends(toks[1]), { 1, 2 })
    h.eq(ends(toks[2]), { 1, 4 })
    h.eq(ends(toks[3]), { 1, 7 })
  end)
  h.it("ends a string after its closing quote, counting escapes as written", function()
    local toks = assert(lexer.tokenize('"a\\nb"'))
    h.eq(ends(toks[1]), { 1, 7 })
  end)
  h.it("ends a multi-line string on its last line", function()
    local toks = assert(lexer.tokenize('"a\nb"'))
    h.eq(ends(toks[1]), { 2, 3 })
  end)
  h.it("counts columns in bytes", function()
    local toks = assert(lexer.tokenize('"é"'))
    h.eq(ends(toks[1]), { 1, 5 })
  end)
end)

h.describe("lexer: recovering mode", function()
  h.it("returns comments with their positions", function()
    local r = lexer.tokenize("x -- note", { recover = true })
    h.eq(r.comments, { { text = "-- note", line = 1, col = 3, end_line = 1, end_col = 10 } })
    h.eq(#r.tokens, 2)
  end)
  h.it("skips an unexpected character and reports it", function()
    local r = lexer.tokenize("let a = 1 @ 2", { recover = true })
    h.eq(#r.diagnostics, 1)
    h.eq(r.diagnostics[1].message, "unexpected character '@'")
    h.eq({ r.diagnostics[1].line, r.diagnostics[1].col }, { 1, 11 })
    local values = {}
    for _, t in ipairs(r.tokens) do values[#values + 1] = t.value end
    h.eq(values, { "let", "a", "=", 1, 2, "<eof>" })
  end)
  h.it("ends an unterminated string at the end of its line", function()
    local r = lexer.tokenize('let s = "abc\nlet t = 1', { recover = true })
    h.eq(#r.diagnostics, 1)
    h.eq(r.diagnostics[1].message, "unterminated string")
    h.eq({ r.diagnostics[1].line, r.diagnostics[1].col }, { 1, 9 })
    local s = r.tokens[4]
    h.eq(s.type, "string")
    h.eq(s.value, "abc")
    h.eq(ends(s), { 1, 13 })
    h.eq({ r.tokens[5].value, r.tokens[5].line, r.tokens[5].col }, { "let", 2, 1 })
    h.eq(r.tokens[8].value, 1)
  end)
  h.it("ends an unterminated string on the last line at the end of the file", function()
    local r = lexer.tokenize('let s = "abc', { recover = true })
    h.eq(#r.diagnostics, 1)
    h.eq(ends(r.tokens[4]), { 1, 13 })
    h.eq(r.tokens[5].type, "eof")
  end)
  h.it("leaves the default mode stopping at the first error", function()
    local toks, err = lexer.tokenize("let a = 1 @ 2")
    h.eq(toks, nil)
    h.eq(err.message, "unexpected character '@'")
  end)
end)
